#!/usr/bin/env python3

import ftplib
import os
import sys
from pathlib import Path

def deploy_mercunmurah():
    """Deploy MercunMurah website to hosting"""
    
    # FTP Configuration
    FTP_HOST = "thexpertbrow.com"
    FTP_USER = "thexpert"
    FTP_PASS = "9-Eu9T35fhUG;i"
    REMOTE_DIR = "/mercunmurah.com"
    LOCAL_DIR = "dist"
    
    print("🌙 Starting MercunMurah.com Deployment...")
    print("=" * 50)
    
    # Check if dist directory exists
    if not os.path.exists(LOCAL_DIR):
        print(f"❌ Error: {LOCAL_DIR} directory not found!")
        print("Please run 'npm run build' first")
        return False
    
    try:
        # Connect to FTP
        print(f"📡 Connecting to {FTP_HOST}...")
        ftp = ftplib.FTP(FTP_HOST)
        ftp.login(FTP_USER, FTP_PASS)
        print("✅ Connected successfully!")
        
        # Change to remote directory
        try:
            ftp.cwd(REMOTE_DIR)
            print(f"📁 Changed to directory: {REMOTE_DIR}")
        except ftplib.error_perm:
            print(f"❌ Cannot access directory: {REMOTE_DIR}")
            return False
        
        # Upload files
        uploaded = 0
        failed = 0
        
        def upload_file(local_path, remote_path):
            nonlocal uploaded, failed
            try:
                with open(local_path, 'rb') as file:
                    ftp.storbinary(f'STOR {remote_path}', file)
                print(f"  ✅ {remote_path}")
                uploaded += 1
            except Exception as e:
                print(f"  ❌ {remote_path} - Error: {e}")
                failed += 1
        
        # Upload root files
        print("\n💰 Uploading MercunMurah files...")
        root_files = [
            'index.html', 'placeholder.svg', 'robots.txt', 'sitemap.xml',
            # Static HTML pages generated by SSG
            'cart.html', 'contact.html', 'fireworks.html', 
            'notfound.html', 'packages.html', 'permits.html', 'testimonials.html'
        ]
        for file in root_files:
            local_file = os.path.join(LOCAL_DIR, file)
            if os.path.exists(local_file):
                upload_file(local_file, file)
        
        # Upload assets directory
        assets_dir = os.path.join(LOCAL_DIR, 'assets')
        if os.path.exists(assets_dir):
            print("\n📦 Uploading assets...")
            # Ensure assets directory exists on remote
            try:
                ftp.mkd('assets')
            except ftplib.error_perm:
                pass  # Directory already exists
            
            for asset_file in os.listdir(assets_dir):
                local_asset = os.path.join(assets_dir, asset_file)
                upload_file(local_asset, f'assets/{asset_file}')
        
        # Create .htaccess for React Router
        print("\n⚙️  Creating .htaccess for MercunMurah...")
        htaccess_content = """# MercunMurah.com Configuration
RewriteEngine On

# React Router - Handle client-side routing
RewriteCond %{REQUEST_FILENAME} !-f
RewriteCond %{REQUEST_FILENAME} !-d
RewriteRule . /index.html [L]

# Directory Index
DirectoryIndex index.html
"""
        
        # Upload .htaccess
        try:
            from io import BytesIO
            htaccess_file = BytesIO(htaccess_content.encode('utf-8'))
            ftp.storbinary('STOR .htaccess', htaccess_file)
            print("  ✅ .htaccess")
            uploaded += 1
        except Exception as e:
            print(f"  ❌ .htaccess - Error: {e}")
            failed += 1
        
        # Close FTP connection
        ftp.quit()
        
        # Summary
        print("\n" + "=" * 50)
        print("💰 MercunMurah.com Deployment Complete!")
        print(f"✅ Files uploaded: {uploaded}")
        print(f"❌ Files failed: {failed}")
        print(f"🎉 Website: https://mercunmurah.com")
        print("Murah dan Berkualiti! 💰✨")
        
        return failed == 0
        
    except Exception as e:
        print(f"❌ Deployment failed: {e}")
        return False

if __name__ == "__main__":
    success = deploy_mercunmurah()
    sys.exit(0 if success else 1)